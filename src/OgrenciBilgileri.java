public class OgrenciBilgileri {

    public int ogrenciNumarasi;
    public String adi;
    public String tc;
    public int yas;

    public OgrenciBilgileri() {
    }

    public OgrenciBilgileri(int ogrenciNumarasi, String adi, String tc, int yas) {
        this.ogrenciNumarasi = ogrenciNumarasi;
        this.adi = adi;
        this.tc = tc;
        this.yas = yas;
    }
}
